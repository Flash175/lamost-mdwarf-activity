
# -*- coding: utf-8 -*-
"""step1_build.py — 只算 §4.9 独有的量：三档二项误差、两套三点拟合的残差与 χ²、逐星内盘拟合。

其余数字（指数/样条诊断、80 分位判据、L 判据、Teff/S/N、6D）已在
复现流程4.4 / 2.5 / 2.6 / 4.1 / 4.5 中核对，本流程不再重复。

输入：数据/新图1_数据_2D分箱.csv、lnf_binfit.csv、lnf_fit_coefs.csv
输出：输出/step1_values.csv、数据/表4.9_拟合形式与误差.csv
"""
import os, io
import numpy as np, pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
D = os.path.join(os.path.dirname(os.path.dirname(HERE)), "数据")
OUT = os.path.join(HERE, "输出"); os.makedirs(OUT, exist_ok=True)

def load(name):
    p = os.path.join(D, name)
    lines = [l for l in open(p, encoding="utf-8-sig", errors="replace").read().splitlines() if not l.startswith("#")]
    return pd.read_csv(io.StringIO("\n".join(lines)))

vals = []
def put(k, v):
    vals.append(dict(item=k, value=float(v)))

B = load("新图1_数据_2D分箱.csv").set_index("zbin")
zb3 = ["<100", "100-200", "200-400"]
f = np.array([float(B.loc[b, "frac"])/100.0 for b in zb3])
z = np.array([float(B.loc[b, "absz_med"]) for b in zb3])
n = np.array([float(B.loc[b, "n"]) for b in zb3])
sig = np.sqrt((1 - f)/(n*f))
sig_round = np.array([0.0043, 0.0063, 0.0079])
for i, lab in enumerate(("0-100", "100-200", "200-400")):
    put("n %s" % lab, n[i]); put("frac %s" % lab, 100*f[i]); put("zmed %s" % lab, z[i])
    put("sig lnf %s" % lab, float(sig[i]))

raw = [l for l in open(os.path.join(D, "lnf_binfit.csv"), encoding="utf-8-sig", errors="replace").read().splitlines()
       if l and not l.startswith("#")]
Fb = pd.DataFrame([l.split(",") for l in raw if l.startswith("fits,")],
                  columns=["section", "fit", "a", "a_se", "b_per_kpc", "b_se", "H_pc", "H_se", "chi2"]).set_index("fit")
for c in ("a", "a_se", "b_per_kpc", "b_se", "H_pc", "H_se", "chi2"):
    Fb[c] = Fb[c].astype(float)
for key, lab in (("unweighted@zmed", "unw"), ("binomial@zmed", "bin")):
    r = Fb.loc[key]
    put("a %s" % lab, float(r.a)); put("b %s" % lab, float(r.b_per_kpc))
    put("H %s" % lab, float(r.H_pc)); put("H se %s" % lab, float(r.H_se))
    put("chi2 stored %s" % lab, float(r.chi2))
    res = np.log(f/np.exp(float(r.a) + float(r.b_per_kpc)*z))
    for i, tag in enumerate(("0-100", "100-200", "200-400")):
        put("resid %s %s" % (lab, tag), float(res[i]))
        put("resid over sig %s %s" % (lab, tag), float(abs(res[i])/sig_round[i]))
    put("chi2 recomputed %s" % lab, float(((res/sig_round)**2).sum()))

C = load("lnf_fit_coefs.csv")
inner = C[C.region.astype(str).str.contains("inner")]
m1 = inner[inner.model.astype(str).str.startswith("M1")]
put("perstar b", float(m1[m1.param == "b_kpc"].coef.iloc[0])/1000.0)
put("perstar b se", float(m1[m1.param == "b_kpc"].se.iloc[0])/1000.0)
put("perstar H", float(m1[m1.param == "b_kpc"].H_pc.iloc[0]))
put("perstar H se", float(m1[m1.param == "b_kpc"].H_se.iloc[0]))


# 逐亚型阈值换算（表2.6）：等效 EW 阈值与"过 EW 未过 L"的比例
L = load("表2.6_Lbol_逐亚型.csv").set_index("spt")
for sp in ("dM0", "dM1", "dM2", "dM3", "dM4", "dM5", "dM6", "dM7", "dM8"):
    put("%s n" % sp, float(L.loc[sp, "n"]))
    put("%s pct EW" % sp, float(L.loc[sp, "pct_EW"]))
    put("%s pct L" % sp, float(L.loc[sp, "pct_lB"]))
    put("%s ew at 1e4" % sp, float(L.loc[sp, "ew_at_1e4"]))
    put("%s gap EW-L" % sp, float(L.loc[sp, "diff_EW_minus_lB"]))
gaps = [float(L.loc[s2, "diff_EW_minus_lB"]) for s2 in ("dM0", "dM1", "dM2", "dM3", "dM4", "dM5", "dM6")]
put("gap monotone dM0-dM6", 1.0 if all(gaps[i + 1] > gaps[i] for i in range(len(gaps) - 1)) else 0.0)
put("gap min dM0-dM6", min(gaps)); put("gap max dM0-dM6", max(gaps))
put("L drop dM0", float(L.loc["dM0", "pct_lA"]) - float(L.loc["dM0", "pct_lB"]))
put("L drop dM1", float(L.loc["dM1", "pct_lA"]) - float(L.loc["dM1", "pct_lB"]))

V = pd.DataFrame(vals).round(6)
V.to_csv(os.path.join(OUT, "step1_values.csv"), index=False, encoding="utf-8-sig")
hdr = ["# 4.9 (own items): binomial errors of the three inner bins, both three-point fits with residuals and",
       "# chi-square, and the per-star logit inner fit. Diagnostics, the 80th-percentile criterion, the L criterion,",
       "# the Teff/S/N drift and the 6D subsample are verified in 4.4 / 2.5 / 2.6 / 4.1 / 4.5.",
       "# inputs: 新图1_数据_2D分箱.csv, lnf_binfit.csv, lnf_fit_coefs.csv",
       "# generated by 复现流程/复现流程4.9/step1_build.py (代码/repro_4p9_build.py)"]
with open(os.path.join(D, "表4.9_拟合形式与误差.csv"), "w", encoding="utf-8-sig", newline="") as fh:
    fh.write("\n".join(hdr) + "\n")
    V.to_csv(fh, index=False)
print(V.to_string(index=False)[:900])
print("  -> 输出/step1_values.csv（%d 项）" % len(V))

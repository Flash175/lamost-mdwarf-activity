
# -*- coding: utf-8 -*-
"""step1_build.py — 4.8 节的量：K 型试点（6,111 原始 / 5,047 清理）的活动比例、χ²、EW 分位与三段分解。

输入：数据/原始输入/processed/dr13/ktype_pilot_clean.csv（5,047 条清理后逐谱表）
      复现流程/复现流程3.6/输出/step1_ktype.csv（原始 6,111 条的逐亚型计数）
      数据/ktype_ew_percentiles.csv、数据/m_side_three_units.csv
输出：输出/step1_values.csv、数据/表4.8_K型试点.csv
"""
import os, io
import numpy as np, pandas as pd
from scipy.stats import chi2, spearmanr

HERE = os.path.dirname(os.path.abspath(__file__))
D = os.path.join(os.path.dirname(os.path.dirname(HERE)), "数据")
OUT = os.path.join(HERE, "输出"); os.makedirs(OUT, exist_ok=True)
K36 = os.path.join(os.path.dirname(HERE), "复现流程3.6", "输出")

def load(name, base=None):
    p = os.path.join(base or D, name)
    lines = [l for l in open(p, encoding="utf-8-sig", errors="replace").read().splitlines() if not l.startswith("#")]
    return pd.read_csv(io.StringIO("\n".join(lines)))

vals = []
def put(k, v):
    vals.append(dict(item=k, value=float(v)))

# 1) 原始 6,111 条：逐亚型计数来自 3.6 流程，χ² 在这里独立重算
R = load("step1_ktype.csv", K36)
R = R[R.n_raw > 0]
n = R.n_raw.values.astype(float); k = R.n_act_raw.values.astype(float)
p = k.sum()/n.sum()
chi2v = float(((k - n*p)**2/(n*p*(1 - p))).sum())
dof = len(n) - 1
put("raw n", n.sum()); put("raw act pct", 100*p)
put("raw chi2", chi2v); put("raw dof", dof); put("raw p", float(chi2.sf(chi2v, dof)))
for s in ("K0", "K1", "K2", "K3", "K4", "K5", "K7"):
    put("raw pct %s" % s, float(R[R.subtype == s].pct_raw.iloc[0]))
put("raw pct max", float(R.pct_raw.max())); put("raw pct min", float(R.pct_raw.min()))

# 2) 清理后 5,047 条：从逐谱表独立重算
S = pd.read_csv(os.path.join(D, "原始输入", "processed", "dr13", "ktype_pilot_clean.csv"),
                low_memory=False, encoding="utf-8-sig")
C = S[S.pass_clean == True].copy()
put("clean n", len(C)); put("clean act pct", 100.0*float(C.active.mean()))
teff = pd.to_numeric(C.teff, errors="coerce")
lab = pd.cut(teff, np.arange(3900, 5600, 100), right=False)
T = C.assign(b=lab).groupby("b", observed=True).active.agg(["size", "mean"])
T["pct"] = 100.0*T["mean"]
put("clean bins", len(T)); put("clean bins n", float(T["size"].sum()))
put("clean pct max", float(T.pct.max())); put("clean pct min", float(T.pct.min()))
ctr = np.array([b.left + 50 for b in T.index], dtype=float)
rho, pv = spearmanr(ctr, T.pct.values)
put("clean spearman rho", float(rho)); put("clean spearman p", float(pv))
for s in ("K0", "K1", "K2", "K3", "K4", "K5", "K7"):
    sub = C[C.subclass == s]
    put("clean pct %s" % s, 100.0*float(sub.active.mean()))

# 3) EW 分位
E = load("ktype_ew_percentiles.csv").set_index("subtype")
put("ew med K0", float(E.loc["K0", "ew_med"])); put("ew med K7", float(E.loc["K7", "ew_med"]))
put("ew med max (all negative?)", float(E.ew_med.max()))
put("ew p90 max", float(E.ew_p90.max()))
put("frac075 min", float(E.frac_gt_075.min())); put("frac075 max", float(E.frac_gt_075.max()))

# 4) 三段分解
M = load("m_side_three_units.csv").set_index("subtype")
for s in ("dM5", "dM7"):
    put("%s spec" % s, float(M.loc[s, "f_spec"]))
    put("%s star" % s, float(M.loc[s, "f_star"]))
    put("%s 2d" % s, float(M.loc[s, "f_2d"]))
    put("%s span" % s, float(max(M.loc[s, ["f_spec", "f_star", "f_2d"]]) - min(M.loc[s, ["f_spec", "f_star", "f_2d"]])))

# 5) 试点选择范围（清理后逐谱表）
for c, lab2 in (("G", "G"), ("snrr", "snr"), ("teff", "teff"), ("logg", "logg")):
    x = pd.to_numeric(S[c], errors="coerce")
    put("sel %s min" % lab2, float(x.min())); put("sel %s max" % lab2, float(x.max()))

V = pd.DataFrame(vals).round(6)
V.to_csv(os.path.join(OUT, "step1_values.csv"), index=False, encoding="utf-8-sig")
hdr = ["# 4.8 sum: K-type pilot (6,111 raw / 5,047 cleaned) activity fractions, chi-square, EW percentiles,",
       "#        the three-unit decomposition of the M-side percentages, and the pilot selection ranges",
       "# inputs: 原始输入/processed/dr13/ktype_pilot_clean.csv, 复现流程3.6/输出/step1_ktype.csv,",
       "#         ktype_ew_percentiles.csv, m_side_three_units.csv",
       "# generated by 复现流程/复现流程4.8/step1_build.py (代码/repro_4p8_build.py)"]
with open(os.path.join(D, "表4.8_K型试点.csv"), "w", encoding="utf-8-sig", newline="") as f:
    f.write("\n".join(hdr) + "\n")
    V.to_csv(f, index=False)
print(V.to_string(index=False)[:1800])
print("  -> 输出/step1_values.csv（%d 项）" % len(V))

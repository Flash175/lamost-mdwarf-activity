
# -*- coding: utf-8 -*-
"""step2b_tau_variant.py — 对流周转时间约定的稳健性：Li (-0.30) vs Wright (+0.31) 二次项。

两者都写成 log tau_c = 2.33 - 1.50 (M/Msun) + q (M/Msun)^2，本文采用 q = -0.30（Li et al. 2024 印刷式），
Wright et al. (2018) 原式为 q = +0.31。这里量化：Ro 标度改变后断点位置、两半 |z| 斜率差与面板差各变多少。

输入：输出/step1_sample.csv
输出：输出/step2b_tau_variant.csv、数据/表3.5_Tau约定对照.csv
"""
import os
import numpy as np, pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__)); OUT = os.path.join(HERE, "输出")
DAT = os.path.join(os.path.dirname(os.path.dirname(HERE)), "数据")
d = pd.read_csv(os.path.join(OUT, "step1_sample.csv"), low_memory=False, encoding="utf-8-sig")
d = d[np.isfinite(d.M) & np.isfinite(d.P) & np.isfinite(d.RHa) & (d.RHa > 0)].copy()
y = np.log10(d.RHa.values)
SAT = 0.132

def tau(M, q):
    return 10.0**(2.33 - 1.50*M + q*M*M)

def argmin_break(ro, grid):
    best = None
    for s in grid:
        m = ro < s
        if m.sum() < 50 or (~m).sum() < 50:
            continue
        c = y[m].mean(); rss = ((y[m] - c)**2).sum()
        x = np.log10(ro[~m]); A = np.vstack([x, np.ones_like(x)]).T
        b, *_ = np.linalg.lstsq(A, y[~m], rcond=None)
        rss += ((y[~m] - A @ b)**2).sum()
        if best is None or rss < best[1]:
            best = (s, rss)
    return best

def slope(ro, mask, sat=SAT):
    m = mask & (ro > sat)
    x = np.log10(ro[m]); yy = y[m]
    A = np.vstack([x, np.ones_like(x)]).T
    b, *_ = np.linalg.lstsq(A, yy, rcond=None)
    se = np.sqrt((((yy - A @ b)**2).sum()/(len(x) - 2))/((x - x.mean())**2).sum())
    return float(b[0]), float(se), int(len(x))

grid = np.logspace(np.log10(0.004), np.log10(0.5), 400)
u = d.usable.values
med = float(np.nanmedian(d.z_gc.values[u]))
low = u & (d.z_gc.values <= med)
high = u & (d.z_gc.values > med)

rows = []
for q, lab in ((-0.30, "Li (-0.30)"), (0.31, "Wright (+0.31)")):
    ro = d.P.values/tau(d.M.values, q)
    s, rss = argmin_break(ro, grid)
    bl, el, nl = slope(ro, low)
    bh, eh, nh = slope(ro, high)
    db = bh - bl; ed = float(np.hypot(el, eh))
    p1, e1, _ = slope(ro, (d.panel == "dM0-dM3").values)
    p2, e2, _ = slope(ro, (d.panel == "dM4-dM6").values)
    rows.append(dict(scheme=lab, quad=q, tau_med=float(np.median(tau(d.M.values, q))),
                     tau_0p3=float(tau(0.3, q)), tau_0p5=float(tau(0.5, q)),
                     ro_sat_argmin=float(s), rss_min=float(rss),
                     beta_low=bl, err_low=el, n_low=nl, beta_high=bh, err_high=eh, n_high=nh,
                     dbeta=db, err_dbeta=ed, sigma=abs(db)/ed,
                     beta_M0M3=p1, beta_M4M6=p2, dbeta_panel=p2 - p1))
T = pd.DataFrame(rows).round(4)
T.to_csv(os.path.join(OUT, "step2b_tau_variant.csv"), index=False, encoding="utf-8-sig")
hdr = ["# 3.5 robustness: convective turnover time convention",
       "# log tau_c = 2.33 - 1.50 (M/Msun) + q (M/Msun)^2; q = -0.30 as printed by Li et al. (2024), q = +0.31 as printed by Wright et al. (2018)",
       "# break fixed at Ro_sat = 0.132 for the slopes; argmin scanned on a 400-point log grid over 0.004-0.5",
       "# generated by 复现流程/复现流程3.5/step2b_tau_variant.py (code/repro_3p5_tau.py)"]
with open(os.path.join(DAT, "表3.5_Tau约定对照.csv"), "w", encoding="utf-8-sig", newline="") as fh:
    fh.write("\n".join(hdr) + "\n")
    T.to_csv(fh, index=False)
print(T[["scheme", "tau_med", "ro_sat_argmin", "dbeta", "err_dbeta", "sigma", "dbeta_panel"]].to_string(index=False))
print("  -> 输出/step2b_tau_variant.csv、数据/表3.5_Tau约定对照.csv")

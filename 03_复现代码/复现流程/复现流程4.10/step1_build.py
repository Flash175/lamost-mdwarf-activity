
# -*- coding: utf-8 -*-
"""step1_build.py — 4.10 节的量：金属度的覆盖与梯度、|Z| 固定下的活动率、亚型退化与通道预算。

输入：数据/金属度_样本与覆盖.csv、金属度_垂直梯度.csv、金属度_固定Z活动率.csv、金属度_组成混杂.csv、
      数据/金属度_亚型中位.csv、金属度_退化诊断.csv、金属度_逐亚型斜率.csv、金属度_通道预算.csv、
      数据/金属度_清洁样本_637973.csv（逐星，用于覆盖数与斜率/相关系数的独立重算）
输出：输出/step1_values.csv、数据/表4.10_金属度通道.csv
"""
import os, io
import numpy as np, pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
D = os.path.join(os.path.dirname(os.path.dirname(HERE)), "数据")
OUT = os.path.join(HERE, "输出"); os.makedirs(OUT, exist_ok=True)

def load(name):
    p = os.path.join(D, name)
    lines = [l for l in open(p, encoding="utf-8-sig", errors="replace").read().splitlines() if not l.startswith("#")]
    return pd.read_csv(io.StringIO("\n".join(lines)))

vals = []
def put(k, v):
    vals.append(dict(item=k, value=float(v)))

# 1) 覆盖与活动率（表）+ 逐星重算覆盖数、中位误差、斜率与相关
C = load("金属度_样本与覆盖.csv").set_index("zb")
ZB = ["<100", "100-200", "200-400", "400-600", "600-1000", ">1000"]
for zb in ZB:
    put("n %s" % zb, float(C.loc[zb, "n"]))
    put("n mh %s" % zb, float(C.loc[zb, "n_mh"]))
    put("cov %s" % zb, float(C.loc[zb, "cov_pct"]))
    put("act all %s" % zb, float(C.loc[zb, "act_all_pct"]))
    put("act mh %s" % zb, float(C.loc[zb, "act_mh_pct"]))
put("n mh total", float(C.n_mh.sum()))
put("cov overall", 100.0*float(C.n_mh.sum())/float(C.n.sum()))
put("decline mh subset", float(C.loc["<100", "act_mh_pct"]) - float(C.loc["200-400", "act_mh_pct"]))

d = pd.read_csv(os.path.join(D, "金属度_清洁样本_637973.csv"), low_memory=False, encoding="utf-8-sig",
                usecols=["m_h", "m_h_err", "absz", "mh_ok"])
mh = pd.to_numeric(d.m_h, errors="coerce"); er = pd.to_numeric(d.m_h_err, errors="coerce")
use = (er.abs() <= 0.25) & mh.between(-2.0, 0.6)
put("n usable", float(use.sum()))
put("usable pct", 100.0*float(use.sum())/len(d))
put("median mh err", float(er[use].median()))
x = pd.to_numeric(d.absz, errors="coerce")[use].values.astype(float)
y = mh[use].values.astype(float)
b, a = np.polyfit(x, y, 1)
put("slope dex per pc", float(b)); put("pearson r", float(np.corrcoef(x, y)[0, 1]))
for lo, hi, lab in ((0, 100, "<100"), (100, 200, "100-200"), (200, 400, "200-400"),
                    (400, 600, "400-600"), (600, 1000, "600-1000"), (1000, 3000, ">1000")):
    s2 = y[(x >= lo) & (x < hi)]
    put("mh med %s" % lab, float(np.median(s2)))
put("gradient first kpc", float(np.median(y[(x < 100)])) - float(np.median(y[(x >= 600) & (x < 1000)])))

# 2) 垂直梯度表（与逐星重算互校）
G = load("金属度_垂直梯度.csv").set_index("zbin")
for zb in ZB:
    put("mh table %s" % zb, float(G.loc[zb, "mh_med"]))

# 3) 固定 |Z| 的四分位与顶减底
Q = load("金属度_固定Z活动率.csv")
qq = Q[Q.quartile != "spearman"].pivot(index="zbin", columns="quartile", values="frac_pct")
for zb in ["<100", "100-200", "200-400", "400-600", "600-1000"]:
    put("q1 %s" % zb, float(qq.loc[zb, "Q1"])); put("q4 %s" % zb, float(qq.loc[zb, "Q4"]))
    put("q4-q1 %s" % zb, float(qq.loc[zb, "Q4"]) - float(qq.loc[zb, "Q1"]))

# 4) 亚型退化与逐亚型斜率
M = load("金属度_亚型中位.csv").set_index("subclass")
for sp in ("dM0", "dM6"):
    put("mh med %s" % sp, float(M.loc[sp, "mh_med"]))
T = load("金属度_退化诊断.csv").set_index("subtype")
put("rho mh teff dM0", float(T.loc["dM0", "rho_mh_teff"])); put("rho mh teff dM5", float(T.loc["dM5", "rho_mh_teff"]))
S = load("金属度_逐亚型斜率.csv").set_index("subtype")
for sp in ("dM0", "dM1", "dM2", "dM3", "dM4", "dM5", "dM6"):
    put("slope %s" % sp, float(S.loc[sp, "b_mh"]))
put("slope dM0 se", float(S.loc["dM0", "se"]))

# 5) 通道预算
B = load("金属度_通道预算.csv").set_index("caliber")
put("beta global", float(B.loc["global(|Z| fixed)", "b_mh"]))
put("beta global se", float(B.loc["global(|Z| fixed)", "b_se"]))
put("delta pp global", float(B.loc["global(|Z| fixed)", "delta_pp"]))
put("dmh", float(B.loc["global(|Z| fixed)", "dm_h_dex"]))
put("beta FE", float(B.loc["fixed effect(subtype+|Z|)", "b_mh"]))
put("beta FE se", float(B.loc["fixed effect(subtype+|Z|)", "b_se"]))
put("delta pp FE", float(B.loc["fixed effect(subtype+|Z|)", "delta_pp"]))

# 6) 四分位组成（<100 pc）
H = load("金属度_组成混杂.csv")
h1 = H[(H.zbin == "<100")]
put("late share q1", float(h1[h1.quartile == "Q1"].late_share_pct.iloc[0]))
put("late share q4", float(h1[h1.quartile == "Q4"].late_share_pct.iloc[0]))
put("dM4 share q1", float(h1[h1.quartile == "Q1"].dM4_share_pct.iloc[0]))
put("dM4 share q4", float(h1[h1.quartile == "Q4"].dM4_share_pct.iloc[0]))

V = pd.DataFrame(vals).round(6)
V.to_csv(os.path.join(OUT, "step1_values.csv"), index=False, encoding="utf-8-sig")
hdr = ["# 4.10 sum: [Fe/H] coverage and vertical gradient, activity at fixed |Z|, subtype degeneracy, channel budget",
       "# inputs: 金属度_*.csv (12 tables) + 金属度_清洁样本_637973.csv (per-star, for the coverage count and the fit)",
       "# generated by 复现流程/复现流程4.10/step1_build.py (代码/repro_4p10_build.py)"]
with open(os.path.join(D, "表4.10_金属度通道.csv"), "w", encoding="utf-8-sig", newline="") as f:
    f.write("\n".join(hdr) + "\n")
    V.to_csv(f, index=False)
print(V.to_string(index=False)[:1200])
print("  -> 输出/step1_values.csv（%d 项）" % len(V))
